// Helper: Thinkific API fetch by email
async function fetchThinkificUser(email) {
    const response = await axios.post(
        THINKIFIC_GRAPHQL_ENDPOINT,
        {
            query: `query GetUserByEmail($email: EmailAddress!) {
        userByEmail(email: $email) {
          id
          email
          firstName
          lastName
          customProfileFields(first: 50) {
            edges { node { value label } }
          }
        }
      }`,
            variables: { email }
        },
        {
            headers: {
                Authorization: `Bearer ${process.env.THINKIFIC_API2_TOKEN}`,
                'X-Auth-Subdomain': process.env.THINKIFIC_SUBDOMAIN,
                'Content-Type': 'application/json'
            }
        }
    );

    if (response.data.errors) {
        console.log('Thinkific errors: ', response);
        throw new Error(response.data.errors.map(err => err.message).join(', '));
    }
    return response.data.data.userByEmail;
}

